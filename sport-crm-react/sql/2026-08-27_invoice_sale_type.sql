-- Тип продажу абонемента: new / renewal / return.
-- Визначається СИСТЕМОЮ автоматично в invoices_api.php при продажу (case 'create'),
-- менеджер не може обрати чи змінити його вручну (щоб не можна було "намалювати" собі KPI).
--
-- Логіка (client_invoices, EFFECTIVE_STATUS_SQL):
--   new     — у клієнта раніше не було жодного абонемента в цьому клубі;
--   renewal — у клієнта Є попередній абонемент зі статусом active/frozen
--             (тобто ще не завершився і не скасований);
--   return  — у клієнта є попередні абонементи, але жоден з них зараз не active/frozen
--             (усі finished/cancelled) — клієнт повернувся після перерви.
--
-- MySQL на цьому хостингу не підтримує ALTER TABLE ... IF NOT EXISTS (див. critical_rules #3) —
-- якщо колонка вже існує, просто пропустіть цей файл.
ALTER TABLE client_invoices
  ADD COLUMN sale_type ENUM('new','renewal','return') NOT NULL DEFAULT 'new' AFTER status;

-- Існуючі (історичні) абонементи залишаються з дефолтним 'new' — поле не перераховується
-- заднім числом, воно працює лише для нових продажів від дати накатки цієї міграції.
