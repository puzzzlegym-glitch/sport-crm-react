-- ============================================================================
-- Що покриває тариф — щоб відвідування списувались лише з відповідного абонемента.
--   gym      — тренажерний зал (самостійні тренування)
--   group    — групові заняття
--   personal — персональні тренування з тренером
--   all      — універсальний: зал + групові (БЕЗ персональних)
-- Правила списання (Attendance::findActiveInvoice):
--   групове заняття   → group, all            (персональний — ніколи)
--   прохід сканером    → gym, all, потім personal (з попередженням)
--   відмітка з тренером → personal, потім all, gym
-- Виконати в phpMyAdmin ДО заливки файлів. Дата: 2026-09-29
-- ============================================================================
ALTER TABLE tariffs
  ADD COLUMN coverage ENUM('all','gym','group','personal') NOT NULL DEFAULT 'all'
      COMMENT 'Що покриває: all=зал+групові, gym, group, personal' AFTER category;

-- Наявні тарифи: з тренером → персональні, решта → універсальний (як і працювали досі).
UPDATE tariffs SET coverage = 'personal' WHERE has_trainer = 1;
