-- ============================================================================
-- Тренер за замовчуванням НЕ бачить касу (залишок, журнал грошових операцій, зміни).
-- Раніше право cash.view було видано тренеру лише тому, що cash_api.php не
-- перевіряв права на читання (див. 2026-08-08_permissions_reality_corrections.sql, п.5).
-- Тепер cash_api.php перевіряє cash.view, тож прибираємо його зі стандарту для тренера.
-- Власник клубу, як і раніше, може увімкнути його на сторінці «Доступ і ролі»
-- (індивідуальні налаштування клубу в club_role_permissions цей скрипт не чіпає).
-- Дата: 2026-09-28
-- ============================================================================
DELETE srp FROM sys_role_permissions srp
JOIN sys_roles r ON r.id = srp.role_id
WHERE r.slug = 'trainer' AND srp.permission_slug = 'cash.view';
